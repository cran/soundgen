#' Naive Bayes
#'
#' An implementation of a Naive Bayes classifier adapted to autocorrelated time
#' series such as the type of nonlinear vocal phenomena in consecutive audio
#' frames. All predictors must be continuous, and the outcome must be
#' categorical. Cases with missing values are not deleted because the posterior
#' probabilities of each outcome class can be calculated from different
#' combinations of predictors on a case-by-case basis. Two optional
#' modifications of a standard Naive Bayes algorithm can be made: (1)
#' classifications can be "clumped" at the final stage, ensuring that every run
#' or "epoch" of a particular predicted class is at least \code{minLength} steps
#' long, and (2) priors can be continuously adapted based on static posterior
#' probabilities of the preceding \code{wlPrior} observations if \code{prior =
#' 'dynamic'}. \code{naiveBayes_train} calculates conditional means and standard
#' deviations per class and global proportions of each class in the dataset.
#' This is mostly useful because the output can be passed on to
#' \code{\link{naiveBayes}} to save time if naiveBayes() is called in a loop
#' with the same training dataset.
#'
#' @param formula model formula of the type outcome ~ predictor1 + predictor2 +
#'   ... (no interactions)
#' @param train either the training dataframe or the output of
#'   \code{\link{naiveBayes_train}}. This data is used to calculate
#'   class-specific distributions of the predictors and prior class
#'   probabilities
#' @param test the test dataframe. This data is used to make predictions - that
#'   is, outcome class probabilities given the values of predictors
#' @param prior "flat" = all classes are equally likely a priori, "static" = use
#'   class probabilities in the training dataset, "dynamic" = update prior
#'   probabilities from static posterior probabilities of \code{wlPrior}
#'   preceding observations
#' @param wlPrior the length of the dynamic-prior window in observations
#' @param wlClumper the minimum length of a predicted class run, enforced by
#'   \code{clumper()}
#' @param runBack if TRUE, the dynamic prior is calculated both forward and
#'   backward and averaged (only has an effect if \code{prior = 'dynamic'})
#' @param plot if TRUE, produces diagnostic plots
#' @export
#' @return A dataframe with new columns: "pr" = the predicted class membership,
#'   "[outcome][class]" = posterior probabilities per class, "like_[class]" =
#'   normalized likelihoods, "prior_[class]" = normalized priors,
#'   "priorF_[class]" / "priorB_[class]" = forward / backward normalized priors
#'   (only filled for \code{prior = 'dynamic'}).
#'
#' @examples
#' set.seed(151)
#' ## create some fake data
#' df = data.frame(group = rep(c(
#'     rep('A', 150), rep('B', 50), rep('A', 120),
#'     rep('A', 100), rep('B', 30), rep('A', 90)
#'   ), 3))
#' df$group = as.factor(df$group)
#' df$x1 = rnorm(nrow(df), mean = ifelse(df$group == 'A', 3, 6), sd = 2)
#' df$x2 = rnorm(nrow(df), mean = ifelse(df$group == 'A', 2, -1), sd = 2)
#' boxplot(x1 ~ group, df)
#' boxplot(x2 ~ group, df)
#'
#' ## train the classifier
#' mod_train = naiveBayes_train(group ~ x1 + x2, train = df)
#' mod_train
#'
#' ## test on new data generated by the same process
#' test = data.frame(group = rep(c(
#'   rep('A', 90), rep('B', 40), rep('A', 150),
#'   rep('B', 40), rep('A', 130), rep('B', 30)
#' ), 2))
#' test$group = as.factor(test$group)
#' test$x1 = rnorm(nrow(test), mean = ifelse(test$group == 'A', 3, 6), sd = 2)
#' test$x2 = rnorm(nrow(test), mean = ifelse(test$group == 'A', 2, -1), sd = 2)
#'
#' # flat priors (same prior probability for each class)
#' nb_flat = naiveBayes(group ~ x1 + x2, train = mod_train, test = test,
#'   prior = 'flat', plot = TRUE)
#' # same as passing 'train' directly to the model, w/o calling naiveBayes_train():
#' nb_flat = naiveBayes(group ~ x1 + x2, train = df, test = test, prior = 'flat')
#' table(nb_flat$group, nb_flat$pr)
#' mean(nb_flat$group == nb_flat$pr)
#'
#' # static priors (use original class proportions as prior class probabilities)
#' nb_static = naiveBayes(group ~ x1 + x2, train = mod_train, test = test,
#'   prior = 'static', wlClumper = NULL, plot = TRUE)
#' table(nb_static$group, nb_static$pr)
#' mean(nb_static$group == nb_static$pr)
#'
#' # specify custom static priors
#' mod_train2 = mod_train
#' mod_train$table
#' mod_train2$table = list(A = .1, B = .9)  # sum to 1
#' nb_static2 = naiveBayes(group ~ x1 + x2, train = mod_train2, test = test,
#'   prior = 'static', wlClumper = NULL, plot = TRUE)
#' mean(nb_static2$group == nb_static2$pr)
#'
#' # if we expect autocorrelation, ie class X is more likely a priori if the
#' # last few observations were also likely to be class X, we can use dynamic
#' # priors and/or clump the predicted classes (the latter imposes strong
#' # constraints on the predictions, but may be worth it if the data is known to
#' # be strongly "clumped", ie if we know classes occur in long'ish runs)
#' nb1 = naiveBayes(group ~ x1 + x2, train = mod_train, test = test,
#'   prior = 'dynamic', wlPrior = 10, plot = TRUE)
#' table(nb1$group, nb1$pr)
#' mean(nb1$group == nb1$pr)
#'
#' nb2 = naiveBayes(group ~ x1 + x2, train = mod_train, test = test,
#'   prior = 'static', wlClumper = 10, plot = TRUE)
#' table(nb2$group, nb2$pr)
#' mean(nb2$group == nb2$pr)
#'
#' nb3 = naiveBayes(group ~ x1 + x2, train = mod_train, test = test,
#'   prior = 'dynamic', wlPrior = 10, wlClumper = 10, plot = TRUE)
#' table(nb3$group, nb3$pr)
#' mean(nb3$group == nb3$pr)
#'
#' # NAs in the data are not a problem
#' test1 = test
#' test1$x1[sample(1:nrow(test1), 100)] = NA
#' test1$x2[sample(1:nrow(test1), 10)] = NA
#' summary(test1)
#'
#' nb4 = naiveBayes(group ~ x1 + x2, train = mod_train, test = test1,
#'   prior = 'dynamic', wlPrior = 10, plot = TRUE)
#' table(nb4$group, nb4$pr, useNA = 'ifany')
#' mean(nb4$group == nb4$pr, na.rm = TRUE)
naiveBayes = function(
    formula,
    train,
    test = train,
    prior = c('static', 'dynamic', 'flat'),
    wlPrior = 3,
    wlClumper = NULL,
    runBack = TRUE,
    plot = FALSE) {
  prior = match.arg(prior)

  # parse model formula
  vars = all.vars(formula)
  if (length(vars) < 2) {
    stop('formula must include an outcome and at least one predictor')
  }
  outcome = vars[1]
  predictors = unique(vars[-1])
  predictors = setdiff(predictors, outcome)

  # check whether train is a dataset or the output of naiveBayes_train()
  train_is_model = !is.data.frame(train) && is.list(train) &&
    !is.null(train$table)
  if (train_is_model) {
    mod_train = train
    if (missing(test)) {
      stop('test must be supplied when train is a trained model')
    }
  } else {
    if (!is.data.frame(train)) {
      stop('train must be a data frame or the output of naiveBayes_train()')
    }
    mod_train = naiveBayes_train(formula, train)
  }
  if (!is.data.frame(test)) {
    stop('test must be a data frame')
  }

  # check predictors
  if (any(!predictors %in% colnames(test))) {
    missing_preds = predictors[which(!predictors %in% colnames(test))]
    warning(paste0('some predictor variables are missing in test: ',
                   paste0(missing_preds, collapse = ', ')))
    predictors = predictors[which(predictors %in% colnames(test))]
  }
  train_predictors = setdiff(names(mod_train), 'table')
  if (any(!predictors %in% train_predictors)) {
    missing_preds = predictors[which(!predictors %in% train_predictors)]
    warning(paste0('some predictor variables are missing in train: ',
                   paste0(missing_preds, collapse = ', ')))
    predictors = predictors[which(predictors %in% train_predictors)]
  }
  if (length(predictors) == 0) {
    stop('no usable predictor variables')
  }

  # check classes
  classes = names(mod_train$table)
  nClasses = length(classes)
  if (nClasses == 0) {
    stop('the trained model contains no outcome classes')
  }
  nObs = nrow(test)
  class_names = paste0(outcome, classes)
  like_names = paste0('like_', outcome, classes)
  prior_names = paste0('prior_', outcome, classes)
  priorF_names = paste0('priorF_', outcome, classes)
  priorB_names = paste0('priorB_', outcome, classes)
  test[, c(class_names, like_names, prior_names,
           priorF_names, priorB_names)] = NA

  # get likelihoods
  likeMat = naiveBayes_likelihood(
    d = test, mod_train = mod_train,
    like_names = like_names, predictors = predictors)
  validRows = attr(likeMat, 'validRows')
  test[, like_names] = likeMat

  # static class probabilities, with a tiny floor to avoid log(0)
  staticProb = pmax(as.numeric(mod_train$table), 0) + 1e-9
  staticProb = staticProb / sum(staticProb)
  logStatic = log(staticProb)

  ## priors
  if (prior == 'dynamic' &&
      (is.null(wlPrior) || length(wlPrior) != 1 ||
       !is.finite(wlPrior) || wlPrior < 1)) {
    prior = 'static'
  }

  if (prior == 'flat') {
    flatProb = rep(1 / nClasses, nClasses) + 1e-9
    flatProb = flatProb / sum(flatProb)
    priorProb = matrix(rep(flatProb, times = nObs),
                       nrow = nObs, ncol = nClasses, byrow = TRUE)

  } else if (prior == 'static') {
    priorProb = matrix(rep(staticProb, times = nObs),
                       nrow = nObs, ncol = nClasses, byrow = TRUE)

  } else if (prior == 'dynamic') {
    # static posterior probabilities are used as dynamic-prior evidence
    logEvidence = sweep(likeMat, 2, logStatic, '+')
    evidence = .rowLogSoftmax(logEvidence)
    if (nObs > 0 && any(!validRows)) {
      evidence[!validRows, ] = NA_real_
    }

    # forward
    priorF_log = naiveBayes_dynamicPrior(
      evidence = evidence, staticProb = staticProb,
      wl = wlPrior, prior_names = prior_names)

    if (runBack) {
      # backward
      if (nObs > 0) {
        myseq = nObs:1
        priorB_log_rev = naiveBayes_dynamicPrior(
          evidence = evidence[myseq, , drop = FALSE],
          staticProb = staticProb, wl = wlPrior,
          prior_names = prior_names)
        priorB_log = priorB_log_rev[myseq, , drop = FALSE]
      } else {
        priorB_log = priorF_log
      }

      # average the forward and backward priors in probability space
      priorProb = (exp(priorF_log) + exp(priorB_log)) / 2
    } else {
      priorProb = exp(priorF_log)
    }

    priorProb = .rowLogSoftmax(log(pmax(priorProb, 1e-9)))
  }

  ## posterior
  logPrior = log(priorProb)
  logPost = likeMat + logPrior
  post = .rowLogSoftmax(logPost)
  if (nObs > 0 && any(!validRows)) {
    post[!validRows, ] = NA_real_
  }
  test[, class_names] = post

  # predict the class
  idx = rep(NA_integer_, nObs)
  if (nObs > 0) {
    validPost = validRows & (rowSums(is.finite(post)) > 0)
    if (any(validPost)) {
      idx[validPost] = max.col(post[validPost, , drop = FALSE],
                               ties.method = 'first')
    }
  }
  test$pr = factor(classes[idx], levels = classes)

  # clump predicted classes
  if (!is.null(wlClumper) && length(wlClumper) == 1 &&
      is.finite(wlClumper) && wlClumper > 1 && nObs > 0) {
    prClumped = test$pr
    idxNA = which(is.na(prClumped))

    if (length(idxNA) > 0) {
      # temporarily fill NAs with the most likely a priori class,
      # which in typical NLP detection corresponds to the default no-NLP class
      fillClass = classes[which.max(staticProb)]
      prClumped[idxNA] = fillClass
      prClumped = clumper(prClumped, minLength = wlClumper)
      prClumped[idxNA] = NA
    } else {
      prClumped = clumper(prClumped, minLength = wlClumper)
    }

    test$pr = factor(prClumped, levels = classes)
  }

  # from log to prob [0, 1] (just to return a neat table and for plotting)
  test[, like_names] = .rowLogSoftmax(likeMat)
  test[, prior_names] = priorProb

  if (prior == 'dynamic') {
    test[, priorF_names] = .rowLogSoftmax(priorF_log)
    if (runBack) {
      test[, priorB_names] = .rowLogSoftmax(priorB_log)
    }
  }

  # plot
  if (plot && nObs > 0) {
    op = par(no.readonly = TRUE)
    par(mfrow = c(2, 2))
    on.exit(par(op))

    if (outcome %in% colnames(test)) {
      truth = test[[outcome]]
      if (!is.factor(truth)) {
        truth = factor(truth, levels = classes)
      }
      truth_int = as.numeric(truth)
    } else {
      truth_int = rep(NA_integer_, nObs)
    }

    # likelihood
    plot(truth_int - 1, type = 'l', main = 'Likelihood',
         xlab = '', ylab = '')
    points(1 - test[, like_names[1]], type = 'l', col = 'blue')

    # priors
    plot(truth_int - 1, type = 'l', main = 'Priors',
         xlab = '', ylab = '')
    points(1 - test[, prior_names[1]], type = 'l', col = 'green')
    if (prior == 'dynamic') {
      points(1 - test[, priorF_names[1]], type = 'l', col = 'blue')
      if (runBack) {
        points(1 - test[, priorB_names[1]], type = 'l', col = 'red')
      }
    }

    # posterior
    plot(truth_int - 1, type = 'l', main = 'Posterior',
         xlab = '', ylab = '')
    points(1 - test[, class_names[1]], type = 'l', col = 'blue')

    # prediction
    plot(truth_int - 1, type = 'l', main = 'Prediction',
         xlab = '', ylab = '')
    points(as.numeric(test$pr) - 1, type = 'l', lty = 2, col = 'blue')
  }

  return(test)
}


#' @describeIn naiveBayes Train a naive Bayes classifier
#' @export
naiveBayes_train = function(formula, train) {
  # parse model formula
  vars = all.vars(formula)
  if (length(vars) < 2) {
    stop('formula must include an outcome and at least one predictor')
  }
  outcome = vars[1]
  predictors = unique(vars[-1])
  predictors = setdiff(predictors, outcome)

  if (!outcome %in% colnames(train)) {
    stop(paste0('outcome variable not found in train: ', outcome))
  }
  missing_preds = setdiff(predictors, colnames(train))
  if (length(missing_preds) > 0) {
    warning(paste0('some predictor variables are missing in train: ',
                   paste0(missing_preds, collapse = ', ')))
    predictors = intersect(predictors, colnames(train))
  }
  if (length(predictors) == 0) {
    stop('no usable predictor variables')
  }
  y = train[[outcome]]
  if (!is.factor(y)) {
    y = factor(y)
  }
  classes = levels(y)
  if (length(classes) == 0) {
    stop('outcome variable has no non-empty classes')
  }

  out = list()
  for (p in predictors) {
    if (!is.numeric(train[[p]])) {
      warning(paste0('predictor is not numeric and was skipped: ', p))
      next
    }
    x = as.numeric(train[[p]])
    x[!is.finite(x)] = NA

    # drop columns with only NAs
    if (!any(!is.na(x))) next

    # class-conditional distributions of each predictor, keeping all classes
    ag_p = data.frame(outcome = classes,
                      mean = NA_real_,
                      sd = NA_real_)

    for (i in seq_along(classes)) {
      xc = x[which(y == classes[i])]
      xc = xc[is.finite(xc)]

      if (length(xc) > 0) {
        mean_i = mean(xc)
        if (is.finite(mean_i)) {
          ag_p$mean[i] = mean_i
        }

        if (length(xc) > 1) {
          sd_i = sd(xc)
          if (is.finite(sd_i) && sd_i > 0) {
            ag_p$sd[i] = sd_i
          }
        }
      }
    }

    # drop predictors for which no class has usable statistics
    if (any(!is.na(ag_p$mean)) || any(!is.na(ag_p$sd))) {
      out[[p]] = ag_p
    }
  }

  tbl = table(y)
  if (sum(tbl) == 0) {
    stop('outcome variable has no non-NA values in train')
  }

  out$table = as.list(tbl / sum(tbl))
  out
}


#' Naive Bayes likelihood
#'
#' A helper function called by \code{\link{naiveBayes}} to calculate the
#' log-likelihood of each observation. Algorithm: for each predictor and class,
#' the log-likelihood is dnorm(observation, mean_per_class, sd_per_class,
#' log = TRUE). Missing predictor values contribute nothing to the log-likelihood
#' sum. Rows with no usable predictor evidence are set to NA.
#'
#' @param d dataframe containing the observations
#' @param mod_train the output of naiveBayes_train()
#' @param like_names the names of variables holding likelihoods
#' @param predictors the names of predictor variables
#' @return Returns a numeric matrix of log-likelihoods, with attribute
#'   'validRows' indicating rows that contain at least one usable predictor.
#' @noRd
naiveBayes_likelihood = function(d, mod_train, like_names, predictors) {
  nObs = nrow(d)
  nClasses = length(like_names)
  classes = names(mod_train$table)

  out = matrix(0, nrow = nObs, ncol = nClasses,
               dimnames = list(NULL, like_names))
  validRows = rep(FALSE, nObs)

  if (nObs == 0 || length(predictors) == 0) {
    out[] = NA_real_
    attr(out, 'validRows') = validRows
    return(out)
  }

  for (p in predictors) {
    if (!is.numeric(d[[p]])) next

    x = as.numeric(d[[p]])
    x[!is.finite(x)] = NA
    ok_x = !is.na(x)
    if (!any(ok_x)) next
    validRows = validRows | ok_x
    stats_p = mod_train[[p]]
    if (is.null(stats_p)) next

    for (c in seq_len(nClasses)) {
      idx = match(classes[c], as.character(stats_p$outcome))
      if (is.na(idx)) next

      mean_p_c = stats_p$mean[idx]
      sd_p_c = stats_p$sd[idx]
      if (!is.finite(mean_p_c) || !is.finite(sd_p_c) || sd_p_c <= 0) next

      # missing values contribute nothing to the log-likelihood sum
      temp = rep(0, nObs)
      temp[ok_x] = dnorm(x[ok_x], mean = mean_p_c, sd = sd_p_c, log = TRUE)

      # keep -Inf as valid evidence of an extremely unlikely value,
      # but do not propagate NA / NaN / +Inf
      temp[is.na(temp) | (is.infinite(temp) & temp > 0)] = 0

      out[, c] = out[, c] + temp
    }
  }

  out[!validRows, ] = NA_real_
  attr(out, 'validRows') = validRows
  return(out)
}


#' Naive Bayes dynamic prior
#'
#' A helper function called by \code{\link{naiveBayes}} to calculate dynamic
#' priors. The prior for each observation is a recency-weighted arithmetic
#' average of static posterior probabilities from preceding observations.
#'
#' @param evidence matrix of static posterior probabilities, one row per
#'   observation
#' @param staticProb vector of static class probabilities
#' @param wl window length, points
#' @param prior_names the names of prior variables
#' @return Returns a numeric matrix of log-priors.
#' @noRd
naiveBayes_dynamicPrior = function(evidence, staticProb, wl, prior_names) {
  evidence = as.matrix(evidence)
  nObs = nrow(evidence)
  nClasses = length(staticProb)

  staticProb = as.numeric(staticProb)
  staticProb[!is.finite(staticProb)] = 0
  staticProb = pmax(staticProb, 1e-9)
  staticProb = staticProb / sum(staticProb)
  logStatic = log(staticProb)

  if (nObs == 0) {
    return(matrix(NA_real_, nrow = 0, ncol = nClasses,
                  dimnames = list(NULL, prior_names)))
  }

  if (nObs == 1) {
    return(matrix(logStatic, nrow = 1, ncol = nClasses, byrow = TRUE,
                  dimnames = list(NULL, prior_names)))
  }

  wl = round(wl)
  if (!is.finite(wl) || wl < 1) wl = 1

  maxLag = min(wl, nObs - 1)

  # weightByAge[1] is the weight of the most recent observation (age 0)
  weightByAge = exp(-12 * ((0:(maxLag - 1)) / max(1, wl - 1))^2)

  prior = matrix(NA_real_, nrow = nObs, ncol = nClasses,
                 dimnames = list(NULL, prior_names))

  # the first observation is just assigned the static prior
  prior[1, ] = logStatic

  for (i in 2:nObs) {
    winIdx = max(1, i - wl):(i - 1)
    L = length(winIdx)

    # weights in the same order as winIdx: oldest to newest
    w = weightByAge[L:1]

    prior_i = staticProb

    for (c in seq_len(nClasses)) {
      vals = evidence[winIdx, c]
      ok = !is.na(vals)

      if (any(ok)) {
        prior_i[c] = sum(w[ok] * vals[ok]) / sum(w[ok])
      }
    }

    prior_i[!is.finite(prior_i)] = staticProb[!is.finite(prior_i)]
    prior_i = pmax(prior_i, 1e-9)
    prior_i = prior_i / sum(prior_i)

    prior[i, ] = log(prior_i)
  }

  return(prior)
}


#' Row-wise log-softmax
#'
#' Internal helper used by naiveBayes() to convert a matrix of log-values into
#' row-wise probabilities. Rows with no finite values are returned as NA.
#'
#' @param logMat numeric matrix of log-values
#' @return Returns a numeric matrix of probabilities with the same dimensions
#'   as \code{logMat}.
#' @noRd
.rowLogSoftmax = function(logMat) {
  logMat = as.matrix(logMat)
  nObs = nrow(logMat)
  nCols = ncol(logMat)

  out = matrix(NA_real_, nrow = nObs, ncol = nCols,
               dimnames = dimnames(logMat))
  if (nObs == 0 || nCols == 0) {
    return(out)
  }
  rowMax = suppressWarnings(apply(logMat, 1, max, na.rm = TRUE))
  valid = is.finite(rowMax)

  if (any(valid)) {
    shifted = exp(sweep(logMat[valid, , drop = FALSE], 1, rowMax[valid], '-'))
    shifted[is.na(shifted)] = 0
    denom = rowSums(shifted, na.rm = TRUE)
    ok = denom > 0 & is.finite(denom)
    shifted[ok, ] = shifted[ok, , drop = FALSE] / denom[ok]
    shifted[!ok, ] = NA_real_
    out[valid, ] = shifted
  }
  out
}
